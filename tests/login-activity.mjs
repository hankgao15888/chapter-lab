import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {mergeLoginEvents,parseLoginEvents} from '../scripts/sync-login-events.mjs';
const {encryptEvent,validEvent}=createRequire(import.meta.url)('../docs/login-activity.js');
const {publicKey,privateKey}=crypto.generateKeyPairSync('rsa',{modulusLength:4096});
const keyId=crypto.createHash('sha256').update(publicKey.export({format:'der',type:'spki'})).digest('hex');
const config={keyId,publicKey:publicKey.export({format:'jwk'})};
const name='学员名字'.repeat(6);
const nameHash=crypto.createHash('sha256').update('chapterlab-name-v1\0'+name).digest('hex');
const event=await encryptEvent(name,nameHash,config);
assert.equal(validEvent(event),true);
assert.equal(JSON.stringify(event).includes(name),false);
assert.equal(JSON.stringify(event).includes(nameHash),false);
const decrypted=JSON.parse(crypto.privateDecrypt({key:privateKey,oaepHash:'sha256',padding:crypto.constants.RSA_PKCS1_OAEP_PADDING},Buffer.from(event.ciphertext,'base64')).toString());
assert.equal(decrypted.name,name);
assert.equal(decrypted.nameHash,nameHash);
assert.equal(decrypted.id,event.id);
const second=await encryptEvent(name,nameHash,config);
assert.notEqual(second.ciphertext,event.ciphertext);
const parsed=parseLoginEvents(JSON.stringify({event:'message',message:JSON.stringify(event)})+'\ninvalid');
assert.deepEqual(parsed,[event]);
assert.equal(parseLoginEvents(JSON.stringify({event:'open',message:JSON.stringify(event)})).length,0);
const merged=mergeLoginEvents({events:[event]},[event,second,{...event,id:'bad'}]);
assert.equal(merged.events.length,2);
assert.deepEqual(mergeLoginEvents(merged,[second,event]),merged);
assert.equal(validEvent({...event,keyId:'invalid'}),false);
console.log('Encrypted student names, private decryption, relay validation and deduplicated login archive passed.');
