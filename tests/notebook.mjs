import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const model=createRequire(import.meta.url)('../docs/notebook-state.js');
const physics='board-physics-2026-Q1',math='board-mathematics-2026-Q1',further='board-furthermathematics-2026-Q1';
const saved={practice:{[physics]:'wrong',[math]:'correct',[further]:'wrong'},papers:[]};
saved.notebook=model.migrate(saved);
assert.equal(model.summary(saved).physics.wrong,1);
assert.equal(model.summary(saved).mathematics.correct,1);
assert.equal(model.summary(saved).furthermathematics.wrong,1);
assert.equal(Object.keys(model.summary(saved)).length,6);
model.update(saved,physics,'correct','physics');
assert.equal(model.summary(saved).physics.wrong,0);
assert.equal(model.summary(saved).physics.correct,1);
const reloaded=JSON.parse(JSON.stringify(saved));
reloaded.notebook=model.migrate(reloaded);
assert.equal(model.includes(reloaded,physics,'correct'),true);
model.update(saved,physics,'wrong','physics');
assert.equal(model.summary(saved).physics.wrong,1);
assert.equal(model.summary(saved).physics.correct,0);
model.update(saved,physics,'clear','physics');
assert.equal(model.summary(saved).physics.total,0);
assert.equal(saved.practice[physics],undefined);
model.update(saved,physics,'correct','physics');
assert.equal(model.summary(saved).physics.total,0,'Correct questions never collected stay outside the notebook');
saved.notebook=model.migrate(saved);
assert.equal(model.summary(saved).physics.total,0);
const restored={practice:{...reloaded.practice},notebook:{}};
model.restore(restored,reloaded);
assert.equal(model.includes(restored,physics,'correct'),true);
assert.equal(model.includes(restored,math,'correct'),true);
model.restore(restored,{practice:{[physics]:'wrong',[math]:'correct'}});
assert.equal(restored.notebook[physics].subject,'physics');
console.log('Notebook legacy migration, six subjects, mastery round-trip, removal and backup restoration passed.');
