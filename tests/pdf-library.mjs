import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),core=require('../docs/pdf-library-core.js');
const chapters=[{id:'p-force',subject:'physics',zh:'力与运动',keywords:['force','acceleration']},{id:'p-wave',subject:'physics',zh:'波动',keywords:['wavelength','frequency']},{id:'m-diff',subject:'mathematics',zh:'微分',keywords:['differentiat','derivative']},{id:'f-complex',subject:'furthermathematics',zh:'复数',keywords:['complex number']}];
const line=(text,top,x=.12)=>({text,top,bottom:top+.02,x});
const pages=[{page:1,lines:[line('Candidate Number',.02),line('1. Calculate the force and acceleration.',.2),line('(a) Determine the acceleration.',.3),line('25 marks',.5),line('1',.98)]},{page:2,lines:[line('Explain your answer.',.15),line('2. State the wavelength and frequency.',.45),line('Leave',.046),line('blank',.058)]},{page:3,lines:[line('Which one statement is correct?',.15),line('3. Differentiate this expression.',.4)]}];
const questions=core.extractQuestions(pages,'physics',chapters);
assert.equal(questions.length,3);
assert.deepEqual(questions[0].parts.map(p=>p.page),[1,2]);
assert.equal(questions[0].parts[0].top,.192);
assert.equal(questions[0].parts.at(-1).bottom,.442);
assert(questions[0].text.includes('Explain your answer.'));
assert(!questions[0].text.includes('State the wavelength'));
assert.deepEqual(questions[0].chapters,['p-force']);
assert.deepEqual(questions[1].chapters,['p-wave']);
assert.equal(core.questionType('(a) Calculate the force\n(b) Calculate the energy'),'calculation','Subparts are not choice options');
assert.equal(core.questionType('A 12\nB 13\nC 14\nD 15'),'choice');
assert.equal(core.questionType('Draw a graph showing the curve.'),'graph');
assert.equal(core.questionType('Describe an experiment and apparatus.'),'practical');
assert.equal(core.questionType('Evaluate the view that taxes reduce output.'),'essay');
assert.deepEqual(core.classify('unrelated content','physics',chapters).chapters,[]);
assert.deepEqual(core.classify('求函数的微分','mathematics',chapters).chapters,['m-diff']);
assert.equal(core.inferSubject('exam.pdf','Further Pure Mathematics F3',chapters),'furthermathematics');
assert.equal(core.inferSubject('biology.pdf','',chapters),'biology');
assert.equal(core.inferSubject('unknown.pdf','',chapters,'economics'),'economics');
const scanned=core.extractQuestions([{page:1,lines:[]},{page:2,lines:[]}],'physics',chapters);
assert.equal(scanned.length,2);assert(scanned.every(q=>q.manual&&!q.chapters.length));
assert.deepEqual(scanned[0].parts,[{page:1,top:0,bottom:1}]);
const noHeadings=core.extractQuestions([{page:1,lines:[line('Some mathematics notes without numbering.',.3)]}],'mathematics',chapters);
assert.equal(noHeadings[0].number,null);
const range=core.validateEdit({number:'Question 7',firstPage:'2',lastPage:'3',chapters:['p-force','m-diff'],type:'calculation'},'physics',chapters,4);
assert.deepEqual(range.chapters,['p-force']);assert.equal(range.parts.length,2);assert(range.reviewed);
assert.throws(()=>core.validateEdit({number:'Q1',firstPage:4,lastPage:2},'physics',chapters,4));
assert.throws(()=>core.validateEdit({number:'Q1',firstPage:0,lastPage:2},'physics',chapters,4));
assert.throws(()=>core.validateEdit({number:'',firstPage:1,lastPage:2},'physics',chapters,4));
const lines=core.linesFromItems([{str:'force',transform:[1,0,0,10,80,700],height:10},{str:'1.',transform:[1,0,0,10,40,700],height:10},{str:'next line',transform:[1,0,0,10,40,660],height:10}],600,800);
assert.equal(lines.length,2);assert.equal(lines[0].text,'1. force');assert.equal(lines[0].top,.1125);
assert(questions.every(q=>q.parts.every(p=>p.bottom>p.top&&p.top>=0&&p.bottom<=1)));
const store=require('../docs/pdf-library-store.js').create(null);
await assert.rejects(store.list('owner'),/本地 PDF 存储/);
console.log('PDF text layout, multi-page splitting, chapter/type suggestions, scan fallback and validated edits passed.');
